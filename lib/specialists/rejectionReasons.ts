export type SpecialistProfileRejectionReasonId =
  (typeof SPECIALIST_PROFILE_REJECTION_REASONS)[number]["id"];

export function buildSpecialistRejectionMessage(
  selectedIds: string[],
  extraNote?: string
): string {
  const selected = SPECIALIST_PROFILE_REJECTION_REASONS.filter((r) =>
    selectedIds.includes(r.id)
  );
  const parts = selected.map((r, i) => `${i + 1}. ${r.label}\n${r.detail}`);
  const note = (extraNote || "").trim();
  if (note) {
    parts.push(`توضیح کارشناس:\n${note}`);
  }
  return parts.join("\n\n");
}
