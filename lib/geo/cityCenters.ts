export function normalizeCityKey(value: string): string {
  return value
    .trim()
    .replace(/ي/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/\u200c/g, "")
    .replace(/\s+/g, "");
}

export function lookupCityCenter(
  cityName: string
): { lat: number; lng: number } | null {
  const raw = cityName.trim();
  if (!raw) return null;
  const direct = IRAN_CITY_CENTERS[raw] || IRAN_CITY_CENTERS[normalizeCityKey(raw)];
  if (direct) return direct;
  const compact = normalizeCityKey(raw);
  for (const [key, coords] of Object.entries(IRAN_CITY_CENTERS)) {
    if (normalizeCityKey(key) === compact) return coords;
  }
  return null;
}

/** Leaflet zoom that comfortably frames a coverage circle of the given radius. */
export function zoomForCoverageRadiusKm(radiusKm: number): number {
  const r = Math.max(5, Math.min(100, Math.round(radiusKm)));
  if (r <= 8) return 13;
  if (r <= 15) return 12;
  if (r <= 25) return 11;
  if (r <= 40) return 10;
  if (r <= 65) return 9;
  return 8;
}
